#  les erreurs de syntaxe
# # ce sont des erreurs qui se produisent lorsque le code n'est pas écrit correctement
# # par exemple, si on oublie de mettre deux-points ou que l'on a mal indenté le code

# Erreur de semantique
# represente une erreur de logique dans le code
# # par exemple, si on essaie d'utiliser une variable qui n'existe pas ou si on essaie de diviser par zéro

# Erreur d'execution
# se produit lorsque le code est écrit correctement mais qu'il y a une erreur lors de l'exécution
# # par exemple, si on essaie d'ouvrir un fichier qui n'existe pas ou si on essaie de diviser par zéro

# Deboguage
# # consiste à trouver et corriger les erreurs dans le code
# # il existe plusieurs outils pour deboguer le code python, comme les IDE, les debogueurs et les outils de test