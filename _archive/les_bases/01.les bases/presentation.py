# python est un langage de programmation interprété, orienté objet et de haut niveau
# il est accessible et facile à apprendre

# Un langage compilé est un langage dont le code est transformé en langage machine avant son exécution
# Cette transformation est faite une seule fois , et produit un fichier exécutable indépendant (ex : .exe)

# Un langage interprété est un langage dont le code est lu et exécuté ligne par ligne par un interpréteur
# Aucune étape de compilation complète n'est faite avant l'exécution , le programme s'exécute directement

# Python est un langage interprété , mais le code source est d'abord transformé en bytecode (.pyc)
# Ce bytecode est ensuite interprété par la machine virtuelle Python (PVM)

# Cela signifie que Python fait une étape de compilation intermédiaire avant l'interprétation


# python est un langage de programmation de haut niveau, 
# ce qui signifie qu'il est plus proche du langage humain que du langage machine

# python est un langage de programmation orienté objet, 
# ce qui signifie qu'il est basé sur le concept d'objets et de classes

# python est un langage de programmation dynamique, 
# ce qui signifie que les types de données sont déterminés au moment de l'exécution


